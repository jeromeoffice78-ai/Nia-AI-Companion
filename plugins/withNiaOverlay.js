const {withAndroidManifest,withDangerousMod}=require('@expo/config-plugins');
const fs=require('fs');
const path=require('path');
const {packageOverlayAssets}=require('../native-overlay/packageAssets.cjs');
module.exports=function withNiaOverlay(config){
 config=withAndroidManifest(config,config=>{
  const manifest=config.modResults.manifest;
  manifest['uses-permission']=manifest['uses-permission']||[];
  for(const permission of ['SYSTEM_ALERT_WINDOW','FOREGROUND_SERVICE','FOREGROUND_SERVICE_SPECIAL_USE','POST_NOTIFICATIONS']){
   const name='android.permission.'+permission;
   if(!manifest['uses-permission'].some(p=>p.$['android:name']===name))manifest['uses-permission'].push({$:{'android:name':name}});
  }
  const application=manifest.application?.[0];
  if(!application)throw new Error('Android application manifest is missing');
  application.service=application.service||[];
  const name='com.nia.companion.NiaOverlayService';
  if(!application.service.some(service=>service.$['android:name']===name))application.service.push({
   $:{'android:name':name,'android:exported':'false','android:foregroundServiceType':'specialUse'},
   property:[{$:{'android:name':'android.app.PROPERTY_SPECIAL_USE_FGS_SUBTYPE','android:value':'User-started floating offline 3D companion avatar, stopped by the user from the overlay or notification'}}],
  });
  return config;
 });
 return withDangerousMod(config,['android',async config=>{
  const root=config.modRequest.platformProjectRoot;
  const pkg='com.nia.companion';
  const folder=path.join(root,'app','src','main','java',...pkg.split('.'));
  fs.mkdirSync(folder,{recursive:true});
  for(const name of ['NiaOverlayModule.java','NiaOverlayPackage.java','NiaOverlayService.java'])
   fs.copyFileSync(path.join(config.modRequest.projectRoot,'native-overlay',name),path.join(folder,name));
  packageOverlayAssets(config.modRequest.projectRoot,path.join(root,'app','src','main','assets','nia-overlay'));
  const application=path.join(folder,'MainApplication.kt');
  if(!fs.existsSync(application))throw new Error('Nia overlay requires MainApplication.kt generated by Expo prebuild');
  let body=fs.readFileSync(application,'utf8');
  const needle='PackageList(this).packages.apply {';
  if(!body.includes('add(NiaOverlayPackage())')){
   if(!body.includes(needle))throw new Error('Unable to register NiaOverlayPackage: unexpected MainApplication.kt layout');
   body=body.replace(needle,needle+'\n              add(NiaOverlayPackage())');
   fs.writeFileSync(application,body);
  }
  return config;
 }]);
};
